/**
 * PLUTON - NASA NAIF SPICE Cosmographia Mission Generator & Exporter
 * Reference: https://naif.jpl.nasa.gov/naif/cosmographia.html
 * Generates authentic Cosmographia 4.x JSON catalogs for Lunar South Pole surface assets,
 * SPICE kernels, antenna sensor frustums, and Gateway NRHO orbit scenarios.
 */

import { LunarSite, HardwareProfile, EphemerisState } from '@/types/pluton';

export interface CosmographiaBundle {
  manifestJson: string;
  spiceKernelsJson: string;
  surfaceAssetJson: string;
  sensorsJson: string;
  pythonScript: string;
}

/**
 * Generates the complete NASA NAIF Cosmographia 4.x JSON Catalog Bundle
 */
export function generateCosmographiaCatalogs(
  site: LunarSite,
  hardware: HardwareProfile,
  ephem: EphemerisState,
  startTime: Date,
  endTime: Date
): CosmographiaBundle {
  const startUtc = startTime.toISOString().replace('T', ' ').slice(0, 19) + ' UTC';
  const endUtc = endTime.toISOString().replace('T', ' ').slice(0, 19) + ' UTC';

  // 1. Master Catalog Manifest
  const manifest = {
    version: '1.0',
    name: `PLUTON Mission - ${site.name} (${hardware.name})`,
    comment:
      'Generated by PLUTON (Polar Lunar Utilities, Topography & Orbital Navigator) NASA JPL / CSA',
    require: [
      'spice_lunar_south_pole.json',
      'surface_asset_lander.json',
      'sensors_telecom_solar.json',
    ],
  };

  // 2. SPICE Kernels Catalog (Generic Solar System + Lunar Orientation Kernels)
  const spiceKernels = {
    version: '1.0',
    name: 'PLUTON SPICE Lunar Kernel Set',
    items: [
      {
        class: 'spice',
        name: 'SPICE_LUNAR_KERNELS',
        kernels: [
          'naif0012.tls', // Leapseconds kernel
          'de421.bsp', // Planetary ephemeris kernel
          'pck00010.tpc', // Planetary constants kernel
          'moon_pa_de421_1900-2050.bpc', // High-precision Moon orientation binary PCK
          'moon_080317.tf', // Lunar coordinate frames (MOON_ME, MOON_PA)
        ],
      },
    ],
  };

  // 3. Surface Spacecraft / Asset Catalog (Anchored at Site Coordinates on MOON_ME)
  const surfaceAsset = {
    version: '1.0',
    name: `PLUTON Surface Asset - ${hardware.name}`,
    items: [
      {
        class: 'spacecraft',
        name: `PLUTON_${hardware.id.toUpperCase().replace(/-/g, '_')}`,
        parent: 'Moon',
        center: 'Moon',
        startTime: startUtc,
        endTime: endUtc,
        trajectory: {
          type: 'FixedPosition',
          frame: 'MOON_ME',
          coordinates: {
            system: 'Planetographic',
            latitude: site.latitude,
            longitude: site.longitude,
            altitude: (site.elevation + hardware.mastHeight) / 1000.0, // km
          },
        },
        bodyFrame: {
          type: 'Topocentric',
          center: 'Moon',
          latitude: site.latitude,
          longitude: site.longitude,
        },
        geometry: {
          type: 'Box',
          dimensions: [hardware.mastHeight * 0.4, hardware.mastHeight * 0.4, hardware.mastHeight],
          color: [0.95, 0.77, 0.25], // Amber / Gold
        },
        label: {
          text: `${hardware.name} [${site.name}]`,
          color: [1.0, 0.9, 0.3],
          size: 11,
          fadeDistance: 50000,
        },
      },
    ],
  };

  // 4. Sensor & Antenna Frustum Catalog (DTE High-Gain Antenna + Gateway NRHO Relay Cone)
  const sensors = {
    version: '1.0',
    name: 'PLUTON Surface Sensors & Communication Beams',
    items: [
      {
        class: 'sensor',
        name: 'DTE_X_BAND_ANTENNA_BEAM',
        parent: `PLUTON_${hardware.id.toUpperCase().replace(/-/g, '_')}`,
        startTime: startUtc,
        endTime: endUtc,
        center: `PLUTON_${hardware.id.toUpperCase().replace(/-/g, '_')}`,
        geometry: {
          type: 'CircularFrustum',
          target: 'Earth',
          range: 405000.0, // km (Moon-Earth distance)
          fieldOfView: 4.8, // degrees beamwidth
          rangeTracking: true,
          frustumColor: [0.1, 0.8, 0.9], // Cyan
          frustumOpacity: 0.25,
          frustumBaseLineWidth: 2,
          onlyVisibleDuringObs: false,
        },
      },
      {
        class: 'sensor',
        name: 'GATEWAY_NRHO_RELAY_CONE',
        parent: `PLUTON_${hardware.id.toUpperCase().replace(/-/g, '_')}`,
        startTime: startUtc,
        endTime: endUtc,
        center: `PLUTON_${hardware.id.toUpperCase().replace(/-/g, '_')}`,
        geometry: {
          type: 'CircularFrustum',
          target: 'Moon',
          range: 70000.0, // km (Gateway Apolune distance)
          fieldOfView: 45.0, // wide elevation capture cone
          rangeTracking: false,
          frustumColor: [0.65, 0.35, 0.95], // Purple
          frustumOpacity: 0.15,
          frustumBaseLineWidth: 1,
          onlyVisibleDuringObs: false,
        },
      },
    ],
  };

  // 5. NAIF Cosmographia Python Automation Script
  const pythonScript = `"""
NASA JPL NAIF Cosmographia Automation Script
Project: PLUTON (Polar Lunar Utilities, Topography & Orbital Navigator)
Site: ${site.name} (${site.latitude.toFixed(2)} deg S, ${site.longitude.toFixed(2)} deg E)
Hardware Twin: ${hardware.name}
Reference: https://naif.jpl.nasa.gov/naif/cosmographia.html
"""

import sys
import cosmographia

def run_pluton_scenario():
    # Connect to running Cosmographia instance
    cosmo = cosmographia.Cosmographia()
    
    # Load PLUTON mission catalog manifest
    cosmo.load_catalog("cosmographia_mission_manifest.json")
    
    # Set observation time to mission epoch
    cosmo.set_time("${startTime.toISOString()}")
    
    # Target Moon and center on South Pole landing site
    cosmo.select_object("PLUTON_${hardware.id.toUpperCase().replace(/-/g, '_')}")
    cosmo.look_at("PLUTON_${hardware.id.toUpperCase().replace(/-/g, '_')}")
    cosmo.set_distance(120.0) # 120 meters overview
    
    # Enable Earth and Sun pointing vectors
    cosmo.show_vectors(True)
    cosmo.show_sensor_frustums(True)
    cosmo.show_orbit("Moon", True)
    
    print("PLUTON scenario loaded successfully in NAIF Cosmographia.")

if __name__ == "__main__":
    run_pluton_scenario()
`;

  return {
    manifestJson: JSON.stringify(manifest, null, 2),
    spiceKernelsJson: JSON.stringify(spiceKernels, null, 2),
    surfaceAssetJson: JSON.stringify(surfaceAsset, null, 2),
    sensorsJson: JSON.stringify(sensors, null, 2),
    pythonScript,
  };
}

/**
 * Triggers a browser download of the Cosmographia scenario files as a combined text/zip or JSON
 */
export function downloadCosmographiaCatalogFile(
  content: string,
  filename: string,
  mimeType: string = 'application/json'
) {
  const blob = new Blob([content], { type: `${mimeType};charset=utf-8;` });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute('download', filename);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
}

